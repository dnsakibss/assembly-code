.MODEL SMALL
.STACK 100H
.DATA
    CR EQU 0DH   
    LF EQU 0AH   
    
MSG1 DB 'ENTER A LOWER CASE LETTER: $'
MSG2 DB 0DH,0AH,'IN UPPER CASE IT IS: $'
CHAR DB ?,'$'
.CODE
MAIN PROC
    
    MOV AX,@DATA
    MOV DS,AX

    LEA DX,MSG1 
    MOV AH,9    ;FOR STRING FUNCTION
    INT 21H     ;DISPLAY FIRST MESSAGE
    
    ;INPUT A CHARACTER AND CONVERT TO UPPER CASE
    MOV AH,1    ;READ CHARACTER FUNCTION 
    INT 21H     ;READ A SMALL LETTER INTO AL
    SUB AL,20H  ;CONVERT IT TO UPPER CASE
    MOV CHAR,AL ;AND STORE IT
    ;DISPLAY ON THE NEXT LINE
    
    LEA DX,MSG2 
    MOV AH,9    ;FOR STRING FUNCTION
    INT 21H
    ;DOS EXIT
    
    MOV AH,2
    MOV DL,CHAR;SHOW THE CONVERTED LETTER
    INT 21H
    
    MOV AH,4CH
    INT 21H     ;DOS EXIT
    
    MAIN ENDP
  END MAIN